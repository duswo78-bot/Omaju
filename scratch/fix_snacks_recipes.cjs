// Fill recipes for remaining new snack names via category when not handcrafted
function buildNewSnack(def) {
  const seed = hash(def.id);
  const moods = pick(MOODS, seed, 2 + (seed % 3));
  const weather = pick(WEATHER, seed + 7, 1 + (seed % 3));
  const snack = {
    id: def.id,
    name_ko: def.name_ko,
    name_en: def.name_en,
    category: def.category,
    spicy: def.spicy,
    greasy: def.greasy,
    sweet: def.sweet,
    bestDrinks: def.bestDrinks.slice(0, 4),
    moods,
    weather,
    tags: def.tags.slice(0, 6),
    recipe: null,
  };
  snack.recipe = getRecipe(snack);
  return snack;
}

// ─── Execute ────────────────────────────────────────────────────────────────
const oldCount = snacks.length;
let rewritten = 0;

for (const snack of snacks) {
  const before = JSON.stringify(snack.recipe);
  snack.recipe = getRecipe(snack);
  if (JSON.stringify(snack.recipe) !== before) rewritten++;
  // validate bestDrinks
  snack.bestDrinks = (snack.bestDrinks || []).filter((id) => alcoholIds.has(id));
  if (snack.bestDrinks.length < 2) {
    const seed = hash(snack.id);
    const fallback = pick([...alcoholIds], seed, 3);
    snack.bestDrinks = [...new Set([...snack.bestDrinks, ...fallback])].slice(0, 4);
  }
}

const existingIds = new Set(snacks.map((s) => s.id));
const existingNames = new Set(snacks.map((s) => s.name_ko));
const added = [];
for (const def of NEW_SNACKS_DEF) {
  if (existingIds.has(def.id) || existingNames.has(def.name_ko)) continue;
  // ensure bestDrinks valid
  def.bestDrinks = (def.bestDrinks || []).filter((id) => alcoholIds.has(id));
  if (def.bestDrinks.length < 2) {
    def.bestDrinks = pick([...alcoholIds], hash(def.id), 3);
  }
  const snack = buildNewSnack(def);
  snacks.push(snack);
  existingIds.add(snack.id);
  existingNames.add(snack.name_ko);
  added.push(snack);
}

// Relations: keep existing, add for new snacks, dedupe
const relKey = (r) => `${r.source}|${r.target}`;
const relMap = new Map();
for (const r of relations) {
  if (!alcoholIds.has(r.source)) continue;
  relMap.set(relKey(r), r);
}
let newRelCount = 0;
for (const snack of added) {
  const drinksList = snack.bestDrinks.slice(0, 4);
  drinksList.forEach((alcId, i) => {
    const r = {
      source: alcId,
      target: snack.id,
      score: scoreFrom(hash(snack.id + alcId) + i, 70, 98),
    };
    const k = relKey(r);
    if (!relMap.has(k)) {
      relMap.set(k, r);
      newRelCount++;
    }
  });
}
const newRelations = [...relMap.values()];

// Validate no generic template leftovers
const genericMarker = /용 주재료 1팩/;
let stillGeneric = 0;
const stepSets = new Set();
for (const s of snacks) {
  if ((s.recipe.ingredients || []).some((ing) => genericMarker.test(ing))) stillGeneric++;
  stepSets.add(JSON.stringify(s.recipe.steps));
  for (const d of s.bestDrinks) {
    if (!alcoholIds.has(d)) throw new Error(`Invalid bestDrink ${d} on ${s.id}`);
  }
}

let missingBest = 0;
for (const s of snacks) {
  if (!s.bestDrinks || s.bestDrinks.length < 2) missingBest++;
  if (!s.recipe || s.recipe.ingredients.length < 5 || s.recipe.steps.length < 4) {
    console.warn('Thin recipe:', s.id, s.name_ko);
  }
}

fs.writeFileSync(snacksPath, JSON.stringify(snacks, null, 2) + '\n', 'utf8');
fs.writeFileSync(relationsPath, JSON.stringify(newRelations, null, 2) + '\n', 'utf8');

