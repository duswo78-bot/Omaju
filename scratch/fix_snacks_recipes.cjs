function recipeFromCategory(snack) {
  const preset = CATEGORY_PRESETS[snack.category] || CATEGORY_PRESETS['기타'];
  const h = hash(snack.id + snack.name_ko);
  const time = preset.time[h % preset.time.length];
  const difficulty = preset.difficulty[h % preset.difficulty.length];
  let ingredients = preset.baseIng(snack.name_ko);
  // Ensure 5-10 ingredients
  const extras = ['통깨', '후추', '참기름 약간', '레몬즙 약간', '버터 한 조각', '청양고추 1개', '깻잎 몇 장'];
  while (ingredients.length < 5) ingredients.push(extras[ingredients.length % extras.length]);
  if (ingredients.length > 10) ingredients = ingredients.slice(0, 10);
  // Make steps unique-ish by injecting seed-based tip
  const tips = [
    '너무 센 불은 피하고 중불 중심으로 익힙니다.',
    '간은 마지막에 한 번 더 보고 맞춥니다.',
    '접시에 담기 전 기름기나 국물 농도를 조절합니다.',
    '술과 함께 내기 직전 향이 좋은 파·깨로 마감합니다.',
  ];
  const steps = preset.steps(snack.name_ko).slice();
  if (steps.length < 4) steps.push(tips[h % tips.length]);
  if (steps.length < 5) steps.push(tips[(h + 1) % tips.length]);
  return { time, difficulty, ingredients, steps: steps.slice(0, 7) };
}

function getRecipe(snack) {
  const byName = HANDCRAFTED[snack.name_ko];
  if (byName) return { ...byName, ingredients: byName.ingredients.slice(), steps: byName.steps.slice() };
  // try without spaces
  const compact = snack.name_ko.replace(/\s+/g, '');
  if (HANDCRAFTED[compact]) {
    const r = HANDCRAFTED[compact];
    return { ...r, ingredients: r.ingredients.slice(), steps: r.steps.slice() };
  }
  return recipeFromCategory(snack);
}

