const ENDING_STRIP = [
  'ㅋㅋㅋㅋ', 'ㅋㅋㅋ', 'ㅋㅋ', 'ㅋ',
  'ㅎㅎㅎㅎ', 'ㅎㅎㅎ', 'ㅎㅎ', 'ㅎ',
  'ㅠㅠㅠ', 'ㅠㅠ', 'ㅜㅜ', 'ㅠ', 'ㅜ',
  '!!!!', '!!!', '!!',
  '~~~~', '~~~', '~~', '~',
  '요오', '여여',
];

/**
 * @param {string} input
 * @returns {{ normalized: string, compact: string }}
 */
export function normalizeKorean(input) {
  let t = String(input || '');

  // 기본 정리
  t = t.replace(/\u200b/g, '');
  t = t.toLowerCase();

  // 자모/이모티콘성 반복 축약
  t = t.replace(/ㅋ{2,}/g, 'ㅋ');
  t = t.replace(/ㅎ{2,}/g, 'ㅎ');
  t = t.replace(/ㅠ{2,}/g, 'ㅠ');
  t = t.replace(/ㅜ{2,}/g, 'ㅜ');
  t = t.replace(/~{2,}/g, '~');
  t = t.replace(/!{2,}/g, '!');
  t = t.replace(/\?{2,}/g, '?');

  // 공백 정리 (너무 붙인 말도 나중에 includes로 잡히게 compact 별도)
  t = t.replace(/\s+/g, ' ').trim();

  // 별칭 치환 (긴 것 우선)
  const sorted = ALIAS_PAIRS.slice().sort((a, b) => b[0].length - a[0].length);
  for (const [from, to] of sorted) {
    if (!from) continue;
    if (t.includes(from)) t = t.split(from).join(to);
  }

  // 말끝 장식 제거
  for (const e of ENDING_STRIP) {
    while (t.endsWith(e)) t = t.slice(0, -e.length).trim();
  }

  // 흔한 말끝 활용 축약
  t = t
    .replace(/해줘여$/g, '해줘')
    .replace(/해주세요$/g, '해줘')
    .replace(/할까요$/g, '할까')
    .replace(/할래요$/g, '할래')
    .replace(/인가요$/g, '인가')
    .replace(/이에요$/g, '이야')
    .replace(/예요$/g, '야')
    .replace(/어요$/g, '어')
    .replace(/아요$/g, '아');

  const normalized = t.replace(/\s+/g, ' ').trim();
  const compact = normalized.replace(/[\s?.,!~ㅋㅎㅠㅜ]/g, '');

  return { normalized, compact };
}

/** 원문 + 정규화본을 합쳐 매칭에 사용 */
export function matchCorpus(rawText) {
  const { normalized, compact } = normalizeKorean(rawText);
  // 원문도 포함해 놓치면 안 되는 표준 표기 보존
  const raw = String(rawText || '');
  const rawCompact = raw.replace(/[\s?.,!~]/g, '');
  return {
    raw,
    normalized,
    compact,
    /** includes 검사용: 정규화·원문 compact 모두 */
    haystack: `${normalized} ${compact} ${raw} ${rawCompact}`.toLowerCase(),
  };
}
